    }
}

function Assert-DestructiveInputs {
    param([string]$ExpectedAction)

    if ($Confirmation -ne 'APPROVE-DROPBOX-DECOMMISSION') {
        throw 'Destructive mode requires -Confirmation APPROVE-DROPBOX-DECOMMISSION.'
    }
    if ([string]::IsNullOrWhiteSpace($ApprovalCsv) -or -not (Test-Path -LiteralPath $ApprovalCsv -PathType Leaf)) {
        throw 'Destructive mode requires a valid -ApprovalCsv path.'
    }

    $rows = @(Import-Csv -LiteralPath $ApprovalCsv)
    if ($rows.Count -eq 0) { throw 'Approval CSV is empty.' }

    $requiredColumns = Get-RequiredApprovalColumns -Action $ExpectedAction
    foreach ($required in $requiredColumns) {
        if ($rows[0].PSObject.Properties.Name -notcontains $required) {
            throw "Approval CSV is missing required column '$required' for action '$ExpectedAction'."
        }
    }

    $approved = @(
        $rows | Where-Object {
            $_.Action -eq $ExpectedAction -and
            ([string]$_.Approval).Trim().ToUpperInvariant() -eq 'APPROVED'
        }
    )

    foreach ($row in $approved) {
        $expectedHash = Get-ApprovalRowHash -Row $row -Action $ExpectedAction
        if (-not [Security.Cryptography.CryptographicOperations]::FixedTimeEquals(
            [Text.Encoding]::ASCII.GetBytes($expectedHash),
            [Text.Encoding]::ASCII.GetBytes(([string]$row.RowHash).Trim().ToLowerInvariant())
        )) {
            throw "Immutable-target validation failed for OperationKey '$($row.OperationKey)'. Regenerate the audit instead of editing target fields."
        }
    }

    if ($MaxItems -gt 0) { $approved = @($approved | Select-Object -First $MaxItems) }
    if ($approved.Count -eq 0) { throw "No rows are approved for action '$ExpectedAction'." }
    return $approved
}

function Add-RowHash {
    param([object]$Row,[string]$Action)
    $Row | Add-Member -NotePropertyName RowHash -NotePropertyValue (Get-ApprovalRowHash -Row $Row -Action $Action) -Force
    return $Row
}

function Invoke-Audit {
    param([string]$Label='Audit')

    $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
    # Always include removed members for owner-state classification. The switch still controls
    # whether removed members are included in shared-link enumeration later in the audit.
    $allMembers = @(Get-TeamMembers -IncludeRemoved $true)
    $members = if ($IncludeRemovedMembers.IsPresent) {
        $allMembers
    }
    else {
        @($allMembers | Where-Object { [string]$_.profile.status.'.tag' -ne 'removed' })
    }

    $memberById = @{}
    foreach ($member in $allMembers) {
        $memberId = [string]$member.profile.team_member_id
        if (-not [string]::IsNullOrWhiteSpace($memberId)) {
            $memberById[$memberId] = $member
        }
    }

    $admin = $allMembers | Where-Object { $_.profile.email -eq $AdminEmail } | Select-Object -First 1
    if (-not $admin) { throw "Admin '$AdminEmail' was not returned by Dropbox." }
    $adminId = [string]$admin.profile.team_member_id

    $teamEmails = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($member in $members) {
        if ($member.profile.email) { [void]$teamEmails.Add([string]$member.profile.email) }
    }

    $folders = @(Get-SharedFolderNamespaces)
    $membershipRows = [Collections.Generic.List[object]]::new()
    $unshareRows = [Collections.Generic.List[object]]::new()
    $auditFailures = [Collections.Generic.List[object]]::new()

    $folderIndex = 0
    foreach ($folder in $folders) {
        $folderIndex++
        Write-Progress -Activity "$($Label): folder memberships" `
            -Status "$folderIndex/$($folders.Count): $($folder.name)" `
            -PercentComplete (($folderIndex/[Math]::Max($folders.Count,1))*100)

        try {
            $pages = @(Get-FolderMembers -SharedFolderId ([string]$folder.namespace_id) -AdminMemberId $adminId)
            $ownerMemberId = $null
            $ownerEmail = $null

            foreach ($page in $pages) {
                $users = @(
                    Get-OptionalProperty `
                        -Object $page `
                        -Name 'users'
                )
                foreach ($entry in $users) {
                    $email = [string](Get-OptionalProperty $entry.user 'email')
                    $accountId = [string](Get-OptionalProperty $entry.user 'account_id')
                    $teamMemberId = [string](Get-OptionalProperty $entry.user 'team_member_id')
                    $access = [string]$entry.access_type.'.tag'
                    $isInherited = [bool](Get-OptionalProperty $entry 'is_inherited')
                    $sameTeamRaw = Get-OptionalProperty $entry.user 'same_team'
                    $sameTeam = if ($null -ne $sameTeamRaw) { [bool]$sameTeamRaw } else { $null }
                    $isExternal = if ($null -ne $sameTeamRaw) {
                        -not [bool]$sameTeamRaw
                    } elseif (-not [string]::IsNullOrWhiteSpace($email)) {
                        -not $teamEmails.Contains($email)
                    } else { $null }

                    if ($access -eq 'owner') { $ownerMemberId=$teamMemberId; $ownerEmail=$email }
                    $eligible = $access -ne 'owner' -and -not $isInherited -and ($accountId -or $email)
                    $key = "RemoveMember|$($folder.namespace_id)|user|$(if($accountId){$accountId}else{$email})"

                    $row = [pscustomobject]@{
                        Action='RemoveMember'; Approval=''; OperationKey=$key
                        FolderName=$folder.name; SharedFolderId=$folder.namespace_id
                        PrincipalType='user'; PrincipalName=$entry.user.display_name
                        PrincipalId=$accountId; Email=$email; TeamMemberId=$teamMemberId
                        AccessType=$access; IsOwner=($access -eq 'owner'); IsInherited=$isInherited
                        SameTeam=$sameTeam; IsExternal=$isExternal
                        EligibleForRemoval=$eligible; LeaveACopy=$false
                        Notes=if($eligible){''}else{'Owner, inherited access, or missing selector. Review only.'}
                    }
                    $membershipRows.Add((Add-RowHash -Row $row -Action 'RemoveMember'))
                }
                $groups = @(
                    Get-OptionalProperty `
                        -Object $page `
                        -Name 'groups'
                )
                foreach ($entry in $groups) {
                    $groupId = [string](Get-OptionalProperty $entry.group 'group_id')
                    $access = [string]$entry.access_type.'.tag'
                    $isInherited = [bool](Get-OptionalProperty $entry 'is_inherited')
                    $sameTeamRaw = Get-OptionalProperty $entry.group 'same_team'
                    $sameTeam = if ($null -ne $sameTeamRaw) { [bool]$sameTeamRaw } else { $null }
                    $eligible = -not $isInherited -and -not [string]::IsNullOrWhiteSpace($groupId)
                    $key = "RemoveMember|$($folder.namespace_id)|group|$groupId"

                    $row = [pscustomobject]@{
                        Action='RemoveMember'; Approval=''; OperationKey=$key
                        FolderName=$folder.name; SharedFolderId=$folder.namespace_id
                        PrincipalType='group'; PrincipalName=$entry.group.group_name
                        PrincipalId=$groupId; Email=''; TeamMemberId=''
                        AccessType=$access; IsOwner=[bool](Get-OptionalProperty $entry.group 'is_owner')
                        IsInherited=$isInherited; SameTeam=$sameTeam
                        IsExternal=if($null -ne $sameTeamRaw){-not [bool]$sameTeamRaw}else{$null}
                        EligibleForRemoval=$eligible; LeaveACopy=$false
                        Notes=if($eligible){''}else{'Inherited group access or missing group ID. Review only.'}
                    }
                    $membershipRows.Add((Add-RowHash -Row $row -Action 'RemoveMember'))
                }

                $invitees = @(
                    Get-OptionalProperty `
                        -Object $page `
                        -Name 'invitees'
                )

                foreach ($entry in $invitees) {
                    $email = [string](Get-OptionalProperty $entry.invitee 'email')
                    $isInherited = [bool](Get-OptionalProperty $entry 'is_inherited')
                    $eligible = -not $isInherited -and -not [string]::IsNullOrWhiteSpace($email)
                    $key = "RemoveMember|$($folder.namespace_id)|invitee|$email"

                    $row = [pscustomobject]@{
                        Action='RemoveMember'; Approval=''; OperationKey=$key
                        FolderName=$folder.name; SharedFolderId=$folder.namespace_id
                        PrincipalType='invitee'; PrincipalName=$email; PrincipalId=''
                        Email=$email; TeamMemberId=''; AccessType=[string]$entry.access_type.'.tag'
                        IsOwner=$false; IsInherited=$isInherited; SameTeam=$false
                        IsExternal=(-not $teamEmails.Contains($email)); EligibleForRemoval=$eligible
                        LeaveACopy=$false
                        Notes=if($eligible){''}else{'Inherited invite or missing email. Review only.'}
                    }
                    $membershipRows.Add((Add-RowHash -Row $row -Action 'RemoveMember'))
                }
            }

            $ownerRecord = if (-not [string]::IsNullOrWhiteSpace($ownerMemberId) -and $memberById.ContainsKey($ownerMemberId)) {
                $memberById[$ownerMemberId]
            }
            else {
                $null
            }

            $ownerStatus = if ($ownerRecord) {
                [string]$ownerRecord.profile.status.'.tag'
            }
            else {
                ''
            }

            $ownerClassification = if ([string]::IsNullOrWhiteSpace($ownerMemberId)) {
                'MissingOwner'
            }
            elseif (-not $ownerRecord) {
                'UnknownOwner'
            }
            else {
                switch ($ownerStatus.ToLowerInvariant()) {
                    'active'    { 'ActiveOwner' }
                    'suspended' { 'SuspendedOwner' }
                    'removed'   { 'RemovedOwner' }
                    default     { 'UnknownOwner' }
                }
            }

            $folderMetadata = $null
            $accessInheritance = ''
            $parentSharedFolderId = ''
            $parentFolderName = ''
            $isInsideTeamFolder = $false
            $isTeamFolder = $false
            $metadataError = ''

            if ($ownerClassification -eq 'ActiveOwner') {
                try {
                    $folderMetadata = Get-SharedFolderMetadata `
                        -SharedFolderId ([string]$folder.namespace_id) `
                        -OwnerTeamMemberId $ownerMemberId

                    $accessInheritance = [string]$folderMetadata.access_inheritance.'.tag'
                    $parentSharedFolderId = [string](Get-OptionalProperty $folderMetadata 'parent_shared_folder_id')
                    $parentFolderName = [string](Get-OptionalProperty $folderMetadata 'parent_folder_name')
                    $isInsideTeamFolder = [bool](Get-OptionalProperty $folderMetadata 'is_inside_team_folder')
                    $isTeamFolder = [bool](Get-OptionalProperty $folderMetadata 'is_team_folder')
                }
                catch {
                    if ($_.Exception.Message -like 'AUTH_FATAL:*') { throw }
                    $metadataError = $_.Exception.Message
                }
            }

            $unshareClassification = if ($ownerClassification -ne 'ActiveOwner') {
                $ownerClassification
            }
            elseif (-not [string]::IsNullOrWhiteSpace($metadataError)) {
                'MetadataUnavailable'
            }
            elseif ($accessInheritance -eq 'inherit') {
                'InheritedAccess'
            }
            elseif ($isTeamFolder) {
                'TeamFolder'
            }
            elseif ($isInsideTeamFolder) {
                'InsideTeamFolder'
            }
            elseif (-not [string]::IsNullOrWhiteSpace($parentSharedFolderId)) {
                'NestedSharedFolder'
            }
            else {
                'IndependentActiveOwner'
            }

            $eligibleForUnshare = $unshareClassification -eq 'IndependentActiveOwner'
            $isArchiveOwner = $ownerEmail -eq 'dropboxarchive@enchantedrock.com'
            $ownerNote = switch ($unshareClassification) {
                'IndependentActiveOwner' { if ($isArchiveOwner) { 'Independent folder owned by the archive account. Confirm retention and backup requirements before approval.' } else { 'Independent folder with an active owner.' } }
                'InheritedAccess' { "Cannot be independently unshared because access is inherited from '$parentFolderName'. Remove access at the controlling parent or remove explicit members and links." }
                'TeamFolder' { 'Team folder. Manage access through the team-folder structure instead of unsharing this namespace.' }
                'InsideTeamFolder' { 'Folder is inside a team folder. Manage access at the controlling team-folder level.' }
                'NestedSharedFolder' { "Nested shared folder controlled by parent shared-folder ID '$parentSharedFolderId'." }
                'MetadataUnavailable' { "Folder metadata could not be inspected: $metadataError" }
                'SuspendedOwner' { 'Orphaned-owner remediation required: owner is suspended.' }
                'RemovedOwner' { 'Orphaned-owner remediation required: owner is removed.' }
                'MissingOwner' { 'Orphaned-owner remediation required: no team-member owner was returned.' }
                default { 'Orphaned-owner remediation required: owner is not an active selectable team member.' }
            }

            $unshareRow = [pscustomobject]@{
                Action='UnshareFolder'; Approval=''
                OperationKey="UnshareFolder|$($folder.namespace_id)"
                FolderName=$folder.name; SharedFolderId=$folder.namespace_id
                OwnerEmail=$ownerEmail; OwnerTeamMemberId=$ownerMemberId
                OwnerStatus=$ownerStatus; OwnerClassification=$ownerClassification
                UnshareClassification=$unshareClassification
                AccessInheritance=$accessInheritance
                ParentSharedFolderId=$parentSharedFolderId
                ParentFolderName=$parentFolderName
                IsInsideTeamFolder=$isInsideTeamFolder
                IsTeamFolder=$isTeamFolder
                IsArchiveOwner=$isArchiveOwner
                EligibleForUnshare=$eligibleForUnshare
                LeaveACopy=$false
                Notes=$ownerNote
            }
            $unshareRows.Add((Add-RowHash -Row $unshareRow -Action 'UnshareFolder'))
        }
        catch {
            if ($_.Exception.Message -like 'AUTH_FATAL:*') { throw }
            $auditFailures.Add([pscustomobject]@{
                AuditArea='FolderMembership'; TargetName=[string]$folder.name
                TargetId=[string]$folder.namespace_id; Error=$_.Exception.Message
                FailedAt=(Get-Date).ToString('o')
            })
            Write-Warning "Membership audit failed for '$($folder.name)' ($($folder.namespace_id)): $($_.Exception.Message)"
        }
    }
    Write-Progress -Activity "$($Label): folder memberships" -Completed

    $linkByUrl = @{}
    $memberIndex = 0
    foreach ($member in $members) {
        $memberIndex++
        $memberId = [string]$member.profile.team_member_id
        Write-Progress -Activity "$($Label): shared links" `
            -Status "$memberIndex/$($members.Count): $($member.profile.email)" `
            -PercentComplete (($memberIndex/[Math]::Max($members.Count,1))*100)

        try {
            foreach ($link in @(Get-AllSharedLinksForMember -TeamMemberId $memberId)) {
                $url = [string]$link.url
                if ([string]::IsNullOrWhiteSpace($url)) { continue }

                $permissions = Get-OptionalProperty $link 'link_permissions'
                $canRevoke = [bool](Get-OptionalProperty $permissions 'can_revoke')
                $resolved = Get-OptionalProperty $permissions 'resolved_visibility'
                $visibility = if ($resolved) { [string]$resolved.'.tag' } else { '' }

                $row = [pscustomobject]@{
                    Action='RevokeLink'; Approval=''; OperationKey="RevokeLink|$url"
                    OwnerEmail=$member.profile.email; OwnerTeamMemberId=$memberId
                    ItemType=[string]$link.'.tag'; ItemName=$link.name; ItemId=$link.id
                    Path=[string](Get-OptionalProperty $link 'path_lower')
                    Url=$url; Visibility=$visibility; CanRevoke=$canRevoke
                    EligibleForRevocation=$canRevoke
                    Notes=if($canRevoke){''}else{[string](Get-OptionalProperty $permissions 'revoke_failure_reason')}
                }
                $row = Add-RowHash -Row $row -Action 'RevokeLink'

                if (-not $linkByUrl.ContainsKey($url) -or
                    (-not (ConvertTo-Boolean $linkByUrl[$url].CanRevoke) -and $canRevoke)) {
                    $linkByUrl[$url] = $row
                }
            }
        }
        catch {
            if ($_.Exception.Message -like 'AUTH_FATAL:*') { throw }
            $auditFailures.Add([pscustomobject]@{
                AuditArea='SharedLinks'; TargetName=[string]$member.profile.email
                TargetId=$memberId; Error=$_.Exception.Message
                FailedAt=(Get-Date).ToString('o')
            })
            Write-Warning "Shared-link audit failed for '$($member.profile.email)': $($_.Exception.Message)"
        }
    }
    Write-Progress -Activity "$($Label): shared links" -Completed

    $linkRows = @($linkByUrl.Values | Sort-Object Url)
    $membershipPath = Join-Path $ReportPath "$Label-MembershipApprovals-$stamp.csv"
    $linksPath = Join-Path $ReportPath "$Label-LinkApprovals-$stamp.csv"
    $unsharePath = Join-Path $ReportPath "$Label-UnshareApprovals-$stamp.csv"
    $failurePath = Join-Path $ReportPath "$Label-AuditFailures-$stamp.csv"

    $membershipRows | Export-Csv -LiteralPath $membershipPath -NoTypeInformation -Encoding utf8
    $linkRows | Export-Csv -LiteralPath $linksPath -NoTypeInformation -Encoding utf8
    $unshareRows | Export-Csv -LiteralPath $unsharePath -NoTypeInformation -Encoding utf8
    $auditFailures | Export-Csv -LiteralPath $failurePath -NoTypeInformation -Encoding utf8

    $auditComplete = $auditFailures.Count -eq 0
    $summary = [pscustomobject]@{
        GeneratedAt=Get-Date; AuditComplete=$auditComplete; AuditFailures=$auditFailures.Count
        TeamMembers=$members.Count; SharedFolders=$folders.Count
        MembershipRows=$membershipRows.Count
        ExternalMembershipRows=@($membershipRows | Where-Object IsExternal).Count
        OwnerRows=@($membershipRows | Where-Object IsOwner).Count
        GroupRows=@($membershipRows | Where-Object PrincipalType -eq 'group').Count
        SharedLinks=$linkRows.Count
        RevocableLinks=@($linkRows | Where-Object EligibleForRevocation).Count
        MembershipApprovalCsv=$membershipPath; LinkApprovalCsv=$linksPath
        ActiveOwnerFolders=@($unshareRows | Where-Object OwnerClassification -eq 'ActiveOwner').Count
        OrphanedOwnerFolders=@($unshareRows | Where-Object OwnerClassification -ne 'ActiveOwner').Count
        IndependentlyUnshareableFolders=@($unshareRows | Where-Object UnshareClassification -eq 'IndependentActiveOwner').Count
        InheritedAccessFolders=@($unshareRows | Where-Object UnshareClassification -eq 'InheritedAccess').Count
        TeamManagedFolders=@($unshareRows | Where-Object { $_.UnshareClassification -in @('TeamFolder','InsideTeamFolder') }).Count
        ArchiveOwnedFolders=@($unshareRows | Where-Object IsArchiveOwner).Count
        UnshareApprovalCsv=$unsharePath; AuditFailureCsv=$failurePath
    }

    $summaryPath = Join-Path $ReportPath "$Label-Summary-$stamp.csv"
    $summary | Export-Csv -LiteralPath $summaryPath -NoTypeInformation -Encoding utf8
    $summary | Format-List

    if (-not $auditComplete) {
        throw "Audit exported partial results but is incomplete. Review '$failurePath'."
    }
}

function Invoke-ApprovedOperations {
    param([string]$Action)

    $rows = @(Assert-DestructiveInputs -ExpectedAction $Action)
    Initialize-Ledger

    $index = 0
    foreach ($row in $rows) {
        $index++
        $key = [string]$row.OperationKey
        Write-Progress -Activity $Action -Status "$index/$($rows.Count): $key" `
            -PercentComplete (($index/[Math]::Max($rows.Count,1))*100)

        if ($script:SuccessKeys.Contains($key)) { continue }

        try {
            switch ($Action) {
                'RevokeLink' {
                    if (-not (ConvertTo-Boolean $row.EligibleForRevocation)) {
                        throw 'Approval row is not eligible for revocation.'
                    }
                    [void](Invoke-DropboxApi `
                        -Uri 'https://api.dropboxapi.com/2/sharing/revoke_shared_link' `
                        -SelectUser $row.OwnerTeamMemberId `
                        -Body @{ url=$row.Url })

                    Add-LedgerRow -Key $key -Action $Action -Target $row.Url `
                        -Status 'Success' -Message 'Shared link revoked.'
                }

                'RemoveMember' {
                    if (-not (ConvertTo-Boolean $row.EligibleForRemoval)) {
                        throw 'Approval row is not eligible for removal.'
                    }
                    if (ConvertTo-Boolean $row.IsOwner) { throw 'Owners cannot be removed by RemoveMembers mode.' }
                    if (ConvertTo-Boolean $row.IsInherited) { throw 'Inherited membership must be removed at its parent.' }
                    if (ConvertTo-Boolean $row.LeaveACopy) { throw 'LeaveACopy must remain False.' }

                    $selector = Get-MemberSelector `
                        -PrincipalType $row.PrincipalType `
                        -PrincipalId $row.PrincipalId `
                        -Email $row.Email

                    $response = Invoke-DropboxApi `
                        -Uri 'https://api.dropboxapi.com/2/sharing/remove_folder_member' `
                        -SelectAdmin $script:AdminMemberId `
                        -Body @{ shared_folder_id=$row.SharedFolderId; member=$selector; leave_a_copy=$false }

                    $result = Complete-DropboxSharingOperation -Response $response -SelectAdmin $script:AdminMemberId
                    Add-LedgerRow -Key $key -Action $Action `
                        -Target "$($row.FolderName): $($row.PrincipalName)" `
                        -Status 'Success' -Message $result.Message -AsyncJobId $result.AsyncJobId
                }

                'UnshareFolder' {
                    if ([string]$row.OwnerClassification -ne 'ActiveOwner') {
                        throw "Folder owner classification is '$($row.OwnerClassification)'. Orphaned-owner remediation is required before unsharing."
                    }
                    if ([string]$row.UnshareClassification -ne 'IndependentActiveOwner') {
                        throw "Folder unshare classification is '$($row.UnshareClassification)'. This namespace cannot be independently unshared."
                    }
                    if ([string]$row.AccessInheritance -eq 'inherit') {
                        throw "Folder access is inherited from '$($row.ParentFolderName)' and cannot be independently unshared."
                    }
                    if ([string]$row.OwnerStatus -ne 'active') {
                        throw "Folder owner status is '$($row.OwnerStatus)'. Only active owners can be selected for unsharing."
                    }
                    if (-not (ConvertTo-Boolean $row.EligibleForUnshare)) {
                        throw 'Approval row is not eligible for unsharing.'
                    }
                    if ([string]::IsNullOrWhiteSpace($row.OwnerTeamMemberId)) {
                        throw 'OwnerTeamMemberId is required to unshare.'
                    }
                    if (ConvertTo-Boolean $row.LeaveACopy) { throw 'LeaveACopy must remain False.' }

                    $response = Invoke-DropboxApi `
                        -Uri 'https://api.dropboxapi.com/2/sharing/unshare_folder' `
                        -SelectUser $row.OwnerTeamMemberId `
                        -Body @{ shared_folder_id=$row.SharedFolderId; leave_a_copy=$false }

                    $result = Complete-DropboxSharingOperation -Response $response -SelectUser $row.OwnerTeamMemberId
                    Add-LedgerRow -Key $key -Action $Action -Target $row.FolderName `
                        -Status 'Success' -Message $result.Message -AsyncJobId $result.AsyncJobId
                }
            }
        }
        catch {
            if ($_.Exception.Message -like 'AUTH_FATAL:*') { throw }
            Add-LedgerRow -Key $key -Action $Action -Target $key `
                -Status 'Failed' -Message $_.Exception.Message
            Write-Warning "$key failed: $($_.Exception.Message)"
        }
    }
    Write-Progress -Activity $Action -Completed
}

function Get-SharedFolderMetadata {
    param(
        [Parameter(Mandatory)]
        [string]$SharedFolderId,

        [Parameter(Mandatory)]
        [string]$OwnerTeamMemberId
    )

    Invoke-DropboxApi `
        -Uri 'https://api.dropboxapi.com/2/sharing/get_folder_metadata' `
        -SelectUser $OwnerTeamMemberId `
        -Body @{
            shared_folder_id = $SharedFolderId
        }
}

Assert-Credentials
$membersForAdmin = @(Get-TeamMembers -IncludeRemoved $false)
$adminForRun = $membersForAdmin |
    Where-Object { $_.profile.email -eq $AdminEmail } |
    Select-Object -First 1

if (-not $adminForRun) { throw "Admin '$AdminEmail' was not returned by Dropbox." }
$script:AdminMemberId = [string]$adminForRun.profile.team_member_id

switch ($Mode) {
    'Audit' { Invoke-Audit -Label 'Audit' }
    'Verify' { Invoke-Audit -Label 'Verify' }
    'RevokeLinks' { Invoke-ApprovedOperations -Action 'RevokeLink' }
    'RemoveMembers' { Invoke-ApprovedOperations -Action 'RemoveMember' }
    'UnshareFolders' { Invoke-ApprovedOperations -Action 'UnshareFolder' }
    'Status' {
        $rows = @(
            if (Test-Path -LiteralPath $LedgerPath) {
                Import-Csv -LiteralPath $LedgerPath
            }
        )

        [pscustomobject]@{
            LedgerRows=$rows.Count
            Success=@($rows | Where-Object Status -eq 'Success').Count
            Failed=@($rows | Where-Object Status -eq 'Failed').Count
            LinksRevoked=@($rows | Where-Object { $_.Action -eq 'RevokeLink' -and $_.Status -eq 'Success' }).Count
            MembersRemoved=@($rows | Where-Object { $_.Action -eq 'RemoveMember' -and $_.Status -eq 'Success' }).Count
            FoldersUnshared=@($rows | Where-Object { $_.Action -eq 'UnshareFolder' -and $_.Status -eq 'Success' }).Count
            AsyncJobsCompleted=@($rows | Where-Object { $_.Status -eq 'Success' -and -not [string]::IsNullOrWhiteSpace($_.AsyncJobId) }).Count
            DropboxRefreshTokenScope=$script:CredentialScopes.DROPBOX_REFRESH_TOKEN
            DropboxAppKeyScope=$script:CredentialScopes.DROPBOX_APP_KEY
            DropboxAppSecretScope=$script:CredentialScopes.DROPBOX_APP_SECRET
            WorkPath=$WorkPath
            LedgerPath=$LedgerPath
        } | Format-List
    }
