function Get-OptionalProperty {
    param([object]$Object,[string]$Name)
    if ($null -ne $Object -and $Object.PSObject.Properties.Name -contains $Name) {
        return $Object.$Name
    }
    return $null
}

function ConvertTo-Boolean {
    param([object]$Value)
    return ([string]$Value).Trim().ToLowerInvariant() -eq 'true'
}

function Assert-Credentials {
    $missing = @()
    if ([string]::IsNullOrWhiteSpace($script:RefreshToken)) { $missing += 'DROPBOX_REFRESH_TOKEN' }
    if ([string]::IsNullOrWhiteSpace($script:AppKey)) { $missing += 'DROPBOX_APP_KEY' }
    if ([string]::IsNullOrWhiteSpace($script:AppSecret)) { $missing += 'DROPBOX_APP_SECRET' }
    if ($missing.Count -gt 0) {
        $scopeSummary = ($script:CredentialScopes.GetEnumerator() | Sort-Object Name | ForEach-Object {
            "$($_.Name)=$($_.Value)"
        }) -join '; '
        throw "Missing environment variables: $($missing -join ', '). Checked User, Process, and Machine scopes. Detected scopes: $scopeSummary"
    }
}

function Get-DropboxAccessToken {
    param([switch]$ForceRefresh)

    if (-not $ForceRefresh -and $script:AccessToken -and $script:TokenExpiresAt -gt (Get-Date).AddMinutes(5)) {
        return $script:AccessToken
    }

    Assert-Credentials
    $basic = [Convert]::ToBase64String(
        [Text.Encoding]::ASCII.GetBytes("$($script:AppKey):$($script:AppSecret)")
    )

    $response = Invoke-RestMethod -Method Post `
        -Uri 'https://api.dropboxapi.com/oauth2/token' `
        -Headers @{ Authorization = "Basic $basic" } `
        -ContentType 'application/x-www-form-urlencoded' `
        -Body @{ grant_type='refresh_token'; refresh_token=$script:RefreshToken }

    $script:AccessToken = [string]$response.access_token
    $script:TokenExpiresAt = (Get-Date).AddSeconds([int]$response.expires_in)
    return $script:AccessToken
}

function Get-HttpStatusCode {
    param([object]$ErrorRecord)
    try { return [int]$ErrorRecord.Exception.Response.StatusCode } catch { return 0 }
}

function Invoke-DropboxApi {
    param(
        [Parameter(Mandatory)][string]$Uri,
        [AllowNull()][object]$Body,
        [string]$SelectUser,
        [string]$SelectAdmin,
        [string]$NamespaceId
    )

    $authRefreshAttempted = $false
    for ($attempt=1; $attempt -le $MaxRetry; $attempt++) {
        try {
            $headers = @{ Authorization = "Bearer $(Get-DropboxAccessToken)" }
            if ($SelectUser) { $headers['Dropbox-API-Select-User'] = $SelectUser }
            if ($SelectAdmin) { $headers['Dropbox-API-Select-Admin'] = $SelectAdmin }
            if ($NamespaceId) {
                $headers['Dropbox-API-Path-Root'] = (@{
                    '.tag'='namespace_id'; namespace_id=$NamespaceId
                } | ConvertTo-Json -Compress)
            }

            $json = if ($null -eq $Body) { 'null' } else {
                $Body | ConvertTo-Json -Depth 15 -Compress
            }

            return Invoke-RestMethod -Method Post -Uri $Uri -Headers $headers `
                -ContentType 'application/json' -Body $json
        }
        catch {
            $status = Get-HttpStatusCode $_
            if ($status -eq 401) {
                if (-not $authRefreshAttempted) {
                    $authRefreshAttempted = $true
                    [void](Get-DropboxAccessToken -ForceRefresh)
                    continue
                }
                throw "AUTH_FATAL: Dropbox authorization failed after token refresh. API: $Uri. $($_.Exception.Message)"
            }

            $retryable = $status -in @(0,408,429) -or $status -ge 500
            if (-not $retryable -or $attempt -eq $MaxRetry) { throw }

            $delay = 0
            try { $delay = [int]$_.Exception.Response.Headers.RetryAfter.Delta.TotalSeconds } catch {}
            if ($delay -le 0) {
                $delay = [int][Math]::Min(300,[Math]::Pow(2,$attempt)+(Get-Random -Minimum 0 -Maximum 4))
            }
            Write-Warning "$Uri failed (HTTP $status), attempt $attempt/$MaxRetry. Retrying in $delay seconds."
            Start-Sleep -Seconds $delay
        }
    }
}

function Wait-DropboxSharingJob {
    param(
        [Parameter(Mandatory)][string]$AsyncJobId,
        [string]$SelectUser,
        [string]$SelectAdmin,
        [ValidateRange(1,3600)][int]$TimeoutSeconds = 1800
    )

    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    do {
        $status = Invoke-DropboxApi `
            -Uri 'https://api.dropboxapi.com/2/sharing/check_job_status' `
            -SelectUser $SelectUser `
            -SelectAdmin $SelectAdmin `
            -Body @{ async_job_id=$AsyncJobId }

        $tag = [string]$status.'.tag'
        switch ($tag) {
            'complete' { return $status }
            'failed' {
                throw "Dropbox async job '$AsyncJobId' failed: $($status | ConvertTo-Json -Depth 10 -Compress)"
            }
            'in_progress' { Start-Sleep -Seconds 2 }
            default { throw "Dropbox async job '$AsyncJobId' returned unexpected status '$tag'." }
        }
    } while ((Get-Date) -lt $deadline)

    throw "Dropbox async job '$AsyncJobId' did not complete within $TimeoutSeconds seconds."
}

function Complete-DropboxSharingOperation {
    param(
        [AllowNull()][object]$Response,
        [string]$SelectUser,
        [string]$SelectAdmin
    )

    if ($null -eq $Response) {
        return [pscustomobject]@{ Message='Completed synchronously.'; AsyncJobId='' }
    }

    $tag = [string](Get-OptionalProperty $Response '.tag')
    if ($tag -eq 'async_job_id') {
        $jobId = [string](Get-OptionalProperty $Response 'async_job_id')
        if ([string]::IsNullOrWhiteSpace($jobId)) {
            throw 'Dropbox returned async_job_id without an async job identifier.'
        }
        [void](Wait-DropboxSharingJob -AsyncJobId $jobId -SelectUser $SelectUser -SelectAdmin $SelectAdmin)
        return [pscustomobject]@{ Message="Async job completed: $jobId"; AsyncJobId=$jobId }
    }

    $message = if ($tag) { "Dropbox result: $tag" } else { 'Operation completed.' }
    return [pscustomobject]@{ Message=$message; AsyncJobId='' }
}

function Get-TeamMembers {
    param([bool]$IncludeRemoved = $IncludeRemovedMembers.IsPresent)

    $response = Invoke-DropboxApi -Uri 'https://api.dropboxapi.com/2/team/members/list_v2' `
        -Body @{ include_removed=$IncludeRemoved; limit=1000 }

    $items = [Collections.Generic.List[object]]::new()
    foreach ($item in $response.members) { $items.Add($item) }

    while ($response.has_more) {
        $response = Invoke-DropboxApi `
            -Uri 'https://api.dropboxapi.com/2/team/members/list/continue_v2' `
            -Body @{ cursor=$response.cursor }
        foreach ($item in $response.members) { $items.Add($item) }
    }
    return $items
}

function Get-SharedFolderNamespaces {
    $response = Invoke-DropboxApi -Uri 'https://api.dropboxapi.com/2/team/namespaces/list' `
        -Body @{ limit=1000 }

    $items = [Collections.Generic.List[object]]::new()
    foreach ($item in $response.namespaces) { $items.Add($item) }

    while ($response.has_more) {
        $response = Invoke-DropboxApi `
            -Uri 'https://api.dropboxapi.com/2/team/namespaces/list/continue' `
            -Body @{ cursor=$response.cursor }
        foreach ($item in $response.namespaces) { $items.Add($item) }
    }

    return @(
        $items |
            Where-Object { $_.namespace_type.'.tag' -eq 'shared_folder' } |
            Sort-Object namespace_id -Unique
    )
}

function Get-FolderMembers {
    param(
        [Parameter(Mandatory)]
        [string]$SharedFolderId,

        [Parameter(Mandatory)]
        [string]$AdminMemberId
    )

    $response = Invoke-DropboxApi `
        -Uri 'https://api.dropboxapi.com/2/sharing/list_folder_members' `
        -SelectAdmin $AdminMemberId `
        -Body @{
            shared_folder_id = $SharedFolderId
            actions          = @()
            limit            = 1000
        }

    $pages = [Collections.Generic.List[object]]::new()
    $pages.Add($response)

    $seenCursors = [Collections.Generic.HashSet[string]]::new(
        [StringComparer]::Ordinal
    )

    while ($true) {
        $cursor = [string](
            Get-OptionalProperty `
                -Object $response `
                -Name 'cursor'
        )

        if ([string]::IsNullOrWhiteSpace($cursor)) {
            break
        }

        if (-not $seenCursors.Add($cursor)) {
            throw "Dropbox returned a repeated folder-member cursor for folder '$SharedFolderId'."
        }

        $response = Invoke-DropboxApi `
            -Uri 'https://api.dropboxapi.com/2/sharing/list_folder_members/continue' `
            -SelectAdmin $AdminMemberId `
            -Body @{
                cursor = $cursor
            }

        $pages.Add($response)
    }

    return $pages
}

function Get-AllSharedLinksForMember {
    param(
        [Parameter(Mandatory)]
        [string]$TeamMemberId
    )

    $response = Invoke-DropboxApi `
        -Uri 'https://api.dropboxapi.com/2/sharing/list_shared_links' `
        -SelectUser $TeamMemberId `
        -Body @{}

    $links = [Collections.Generic.List[object]]::new()

    $initialLinks = @(
        Get-OptionalProperty `
            -Object $response `
            -Name 'links'
    )

    foreach ($link in $initialLinks) {
        $links.Add($link)
    }

    $seenCursors = [Collections.Generic.HashSet[string]]::new(
        [StringComparer]::Ordinal
    )

    while ($true) {
        $hasMoreValue = Get-OptionalProperty `
            -Object $response `
            -Name 'has_more'

        $hasMore = $null -ne $hasMoreValue -and [bool]$hasMoreValue

        if (-not $hasMore) {
            break
        }

        $cursor = Get-OptionalProperty `
                -Object $response `
                -Name 'cursor'
        

        if ([string]::IsNullOrWhiteSpace($cursor)) {
            throw "Dropbox reported more shared-link results but did not return a cursor for member '$TeamMemberId'."
        }

        if (-not $seenCursors.Add($cursor)) {
            throw "Dropbox returned a repeated shared-link cursor for member '$TeamMemberId'."
        }

        $response = Invoke-DropboxApi `
            -Uri 'https://api.dropboxapi.com/2/sharing/list_shared_links' `
            -SelectUser $TeamMemberId `
            -Body @{
                cursor = $cursor
            }

        $pageLinks = @(
            Get-OptionalProperty `
                -Object $response `
                -Name 'links'
        )

        foreach ($link in $pageLinks) {
            $links.Add($link)
        }
    }

    return $links
}

function Get-MemberSelector {
    param([string]$PrincipalType,[string]$PrincipalId,[string]$Email)

    if ($PrincipalType -in @('user','group') -and $PrincipalId) {
        return @{ '.tag'='dropbox_id'; dropbox_id=$PrincipalId }
    }
    if ($Email) { return @{ '.tag'='email'; email=$Email } }
    throw "Cannot construct Dropbox member selector for type '$PrincipalType'."
}

function Get-ImmutableValue {
    param([object]$Row,[string]$Name)
    $value = Get-OptionalProperty $Row $Name
    if ($null -eq $value) { return '' }
    return ([string]$value).Trim()
}

function Get-ApprovalRowHash {
    param([object]$Row,[string]$Action)

    $fields = switch ($Action) {
        'RevokeLink' { @('Action','OperationKey','OwnerTeamMemberId','Url','EligibleForRevocation') }
        'RemoveMember' { @('Action','OperationKey','SharedFolderId','PrincipalType','PrincipalId','Email','EligibleForRemoval','IsOwner','IsInherited','LeaveACopy') }
        'UnshareFolder' { @('Action','OperationKey','SharedFolderId','OwnerTeamMemberId','OwnerStatus','OwnerClassification','UnshareClassification','AccessInheritance','ParentSharedFolderId','ParentFolderName','IsInsideTeamFolder','IsTeamFolder','EligibleForUnshare','LeaveACopy') }
        default { throw "Unsupported approval action '$Action'." }
    }

    $canonical = ($fields | ForEach-Object {
        $name = $_
        "$name=$(Get-ImmutableValue -Row $Row -Name $name)"
    }) -join "`n"

    $sha = [Security.Cryptography.SHA256]::Create()
    try {
        $hash = $sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($canonical))
        return ([Convert]::ToHexString($hash)).ToLowerInvariant()
    }
    finally { $sha.Dispose() }
}

function Add-LedgerRow {
    param(
        [string]$Key,[string]$Action,[string]$Target,[string]$Status,
        [string]$Message,[string]$AsyncJobId=''
    )

    [pscustomobject]@{
        Timestamp=(Get-Date).ToString('o')
        Key=$Key
        Action=$Action
        Target=$Target
        Status=$Status
        AsyncJobId=$AsyncJobId
        Message=$Message
    } | Export-Csv -LiteralPath $LedgerPath -Append -NoTypeInformation -Encoding utf8

    if ($Status -eq 'Success') { [void]$script:SuccessKeys.Add($Key) }
}

function Initialize-Ledger {
    if (Test-Path -LiteralPath $LedgerPath) {
        foreach ($row in @(Import-Csv -LiteralPath $LedgerPath | Where-Object Status -eq 'Success')) {
            if ($row.Key) { [void]$script:SuccessKeys.Add([string]$row.Key) }
        }
    }
}

function Get-RequiredApprovalColumns {
    param([string]$Action)
    switch ($Action) {
        'RevokeLink' { return @('Action','Approval','OperationKey','RowHash','OwnerTeamMemberId','Url','EligibleForRevocation') }
        'RemoveMember' { return @('Action','Approval','OperationKey','RowHash','SharedFolderId','PrincipalType','PrincipalId','Email','EligibleForRemoval','IsOwner','IsInherited','LeaveACopy') }
        'UnshareFolder' { return @('Action','Approval','OperationKey','RowHash','SharedFolderId','OwnerTeamMemberId','OwnerStatus','OwnerClassification','UnshareClassification','AccessInheritance','ParentSharedFolderId','ParentFolderName','IsInsideTeamFolder','IsTeamFolder','EligibleForUnshare','LeaveACopy') }
